"""Run one selected pytest case and serialize a bounded mock trace."""

import inspect
import json
import math
import os
import re
import sys
from itertools import islice
from pathlib import Path
from unittest.mock import Base, Mock, _Call, _CallList

REPORT_BYTES = 8192
_MAX_MOCKS = 4
_MAX_CALLS = 12
_MAX_ITEMS = 6
_MAX_DEPTH = 2
_REDACTED = "<redacted>"
_NAME = re.compile(r"[A-Za-z_][A-Za-z_0-9]{0,47}")
_INSTANCE_DICT = Base.__dict__["__dict__"]


def _identifier(value):
    return type(value) is str and _NAME.fullmatch(value)


def _method(value):
    return (
        type(value) is str
        and len(value) <= 96
        and (not value or all(_identifier(part) for part in value.split(".")))
    )


def _number(value):
    return (
        type(value) is bool
        or (type(value) is int and value.bit_length() <= 53)
        or (type(value) is float and math.isfinite(value))
    )


def _argument(value, depth=0):
    if _number(value):
        return value
    if (
        (type(value) is tuple or type(value) is list)
        and depth < _MAX_DEPTH
        and len(value) <= _MAX_ITEMS
    ):
        return [_argument(item, depth + 1) for item in value]
    return _REDACTED


def _valid_argument(value, depth=0):
    return (
        _number(value)
        or (type(value) is str and value == _REDACTED)
        or (
            type(value) is list
            and depth < _MAX_DEPTH
            and len(value) <= _MAX_ITEMS
            and all(_valid_argument(item, depth + 1) for item in value)
        )
    )


def _mock_calls(value):
    calls = _INSTANCE_DICT.__get__(value).get("_mock_mock_calls")
    if type(calls) is not _CallList or len(calls) > _MAX_CALLS:
        return None
    result = []
    for call in calls:
        if type(call) is not _Call or tuple.__len__(call) != 3:
            return None
        method, args, kwargs = call
        if (
            not _method(method)
            or type(args) is not tuple
            or type(kwargs) is not dict
            or max(len(args), len(kwargs)) > _MAX_ITEMS
            or not all(_identifier(key) for key in kwargs)
        ):
            return None
        result.append(
            [
                method,
                [_argument(arg) for arg in args],
                {key: _argument(arg) for key, arg in kwargs.items()},
            ]
        )
    return result


def _locals_trace(frame):
    traces = {}
    for name, value in islice(frame.f_locals.items(), 64):
        if _identifier(name) and issubclass(type(value), Mock):
            if (calls := _mock_calls(value)) is not None:
                traces[name] = calls
                if len(traces) == _MAX_MOCKS:
                    break
    return traces


def decode_traces(output):
    """Validate only the schema generated by this probe before using its output."""
    if len(output) > REPORT_BYTES:
        return None
    try:
        traces = json.loads(output)
    except (ValueError, RecursionError):
        return None
    if type(traces) is not dict or len(traces) > _MAX_MOCKS:
        return None
    for name, calls in traces.items():
        if not _identifier(name) or type(calls) is not list or len(calls) > _MAX_CALLS:
            return None
        for call in calls:
            if type(call) is not list or len(call) != 3:
                return None
            method, args, kwargs = call
            if (
                not _method(method)
                or type(args) is not list
                or type(kwargs) is not dict
                or max(len(args), len(kwargs)) > _MAX_ITEMS
                or not all(_valid_argument(arg) for arg in args)
                or not all(
                    _identifier(key) and _valid_argument(arg)
                    for key, arg in kwargs.items()
                )
            ):
                return None
    return traces


def _run_pytest(node):
    import pytest

    path = Path(node.split("::", 1)[0]).resolve()

    class Probe:
        reports = ()
        traces = None

        def pytest_collection_finish(self, session):
            if [item.nodeid for item in session.items] != [node]:
                pytest.exit("Expected precisely one selected test", returncode=4)

        @pytest.hookimpl(wrapper=True, tryfirst=True)
        def pytest_runtest_call(self, item):
            function = inspect.unwrap(item.obj)
            code = getattr(function, "__code__", None)
            unsupported = (
                inspect.CO_COROUTINE
                | inspect.CO_ASYNC_GENERATOR
                | inspect.CO_GENERATOR
                | inspect.CO_ITERABLE_COROUTINE
            )
            if (
                code is None
                or code.co_flags & unsupported
                or Path(code.co_filename).resolve() != path
                or sys.getprofile() is not None
            ):
                return (yield)
            events = 0

            def profile(frame, event, _value):
                nonlocal events
                events += 1
                if events >= 100_000:
                    self.traces = None
                    sys.setprofile(None)
                elif event == "return" and frame.f_code is code:
                    self.traces = _locals_trace(frame)
                    sys.setprofile(None)

            sys.setprofile(profile)
            try:
                return (yield)
            finally:
                sys.setprofile(None)

        def pytest_runtest_logreport(self, report):
            if report.nodeid == node and not hasattr(report, "wasxfail"):
                self.reports += ((report.when, report.outcome),)

    probe = Probe()
    os.environ.pop("PYTEST_ADDOPTS", None)
    sys.path.insert(0, os.getcwd())
    status = pytest.main(
        ["-o", "addopts=", "-p", "no:cacheprovider", "--", node],
        plugins=[probe],
    )
    expected = "passed" if status == 0 else "failed"
    if status in (0, 1) and probe.reports == (
        ("setup", "passed"),
        ("call", expected),
        ("teardown", "passed"),
    ):
        return int(status), probe.traces
    return 4, None


def _main(node):
    # Keep all test output, even native stdout/stderr, out of the report stream.
    with os.fdopen(os.dup(1), "w") as report, open(os.devnull, "wb") as sink:
        os.dup2(sink.fileno(), 1)
        os.dup2(sink.fileno(), 2)
        status, traces = _run_pytest(node)
        if traces is not None:
            payload = json.dumps(traces, separators=(",", ":"), allow_nan=False)
            if len(payload) <= REPORT_BYTES:
                report.write(payload)
        return status


if __name__ == "__main__":
    sys.exit(_main(sys.argv[1]))
