"""Run one selected pytest case and serialize a bounded mock trace."""

import hashlib
import inspect
import json
import math
import os
import re
import sys
from itertools import islice
from pathlib import Path
from unittest.mock import Base, Mock, _Call, _CallList

REPORT_BYTES = 8192
COUNTER_REPORT_BYTES = 2 * REPORT_BYTES
_MAX_MOCKS = 4
_MAX_CALLS = 12
_MAX_ITEMS = 6
_MAX_DEPTH = 2
_REDACTED = "<redacted>"
_NAME = re.compile(r"[A-Za-z_][A-Za-z_0-9]{0,47}")
_INSTANCE_DICT = Base.__dict__["__dict__"]


def _identifier(value):
    return type(value) is str and _NAME.fullmatch(value)


def _method(value):
    return (
        type(value) is str
        and len(value) <= 96
        and (not value or all(_identifier(part) for part in value.split(".")))
    )


def _number(value):
    return (
        type(value) is bool
        or (type(value) is int and value.bit_length() <= 53)
        or (type(value) is float and math.isfinite(value))
    )


def _argument(value, depth=0):
    if _number(value):
        return value
    if (
        (type(value) is tuple or type(value) is list)
        and depth < _MAX_DEPTH
        and len(value) <= _MAX_ITEMS
    ):
        return [_argument(item, depth + 1) for item in value]
    return _REDACTED


def _valid_argument(value, depth=0):
    return (
        _number(value)
        or (type(value) is str and value == _REDACTED)
        or (
            type(value) is list
            and depth < _MAX_DEPTH
            and len(value) <= _MAX_ITEMS
            and all(_valid_argument(item, depth + 1) for item in value)
        )
    )


def _mock_calls(value):
    calls = _INSTANCE_DICT.__get__(value).get("_mock_mock_calls")
    if type(calls) is not _CallList or len(calls) > _MAX_CALLS:
        return None
    result = []
    for call in calls:
        if type(call) is not _Call or tuple.__len__(call) != 3:
            return None
        method, args, kwargs = call
        if (
            not _method(method)
            or type(args) is not tuple
            or type(kwargs) is not dict
            or max(len(args), len(kwargs)) > _MAX_ITEMS
            or not all(_identifier(key) for key in kwargs)
        ):
            return None
        result.append(
            [
                method,
                [_argument(arg) for arg in args],
                {key: _argument(arg) for key, arg in kwargs.items()},
            ]
        )
    return result


def _locals_trace(frame):
    traces = {}
    for name, value in islice(frame.f_locals.items(), 64):
        if _identifier(name) and issubclass(type(value), Mock):
            if (calls := _mock_calls(value)) is not None:
                traces[name] = calls
                if len(traces) == _MAX_MOCKS:
                    break
    return traces


def decode_traces(output):
    """Validate only the schema generated by this probe before using its output."""
    if len(output) > REPORT_BYTES:
        return None
    try:
        traces = json.loads(output)
    except (ValueError, RecursionError):
        return None
    if type(traces) is not dict or len(traces) > _MAX_MOCKS:
        return None
    for name, calls in traces.items():
        if not _identifier(name) or type(calls) is not list or len(calls) > _MAX_CALLS:
            return None
        for call in calls:
            if type(call) is not list or len(call) != 3:
                return None
            method, args, kwargs = call
            if (
                not _method(method)
                or type(args) is not list
                or type(kwargs) is not dict
                or max(len(args), len(kwargs)) > _MAX_ITEMS
                or not all(_valid_argument(arg) for arg in args)
                or not all(
                    _identifier(key) and _valid_argument(arg)
                    for key, arg in kwargs.items()
                )
            ):
                return None
    return traces


def _numeric_shape(value, depth=0):
    if _number(value):
        return value
    if type(value) not in (list, tuple) or depth >= _MAX_DEPTH or len(value) > _MAX_ITEMS:
        return None
    items = [_numeric_shape(item, depth + 1) for item in value]
    return [type(value).__name__, *items] if None not in items else None


class _CallbackTrace:
    """Keep only bounded call counts and keyed numeric fingerprints."""

    def __init__(self, node, paths, key):
        test = node.partition("::")[0]
        self.test_paths = {test, str(Path(test).resolve())}
        self.callers = set(paths) | {str(Path(path).resolve()) for path in paths}
        self.mock_path = sys.modules["unittest.mock"].__file__
        self.key = bytes.fromhex(key)
        self.codes = {}
        self.stats = {}
        self.complete = self.overflow = False

    def observe(self, frame, test_code):
        code = frame.f_code
        if (
            self.overflow or code is test_code or code.co_filename not in self.test_paths
            or not _identifier(code.co_name)
        ):
            return
        caller = frame.f_back
        for _ in range(8):
            if caller is None or caller.f_code.co_filename != self.mock_path:
                break
            caller = caller.f_back
        if caller is None or caller.f_code.co_filename not in self.callers:
            return
        if self.codes.setdefault(code.co_name, code) is not code or len(self.codes) > _MAX_MOCKS:
            self.overflow = True
            return
        stat = self.stats.setdefault(code.co_name, [0, []])
        stat[0] += 1
        if len(stat[1]) >= _MAX_CALLS:
            return
        count = code.co_argcount + code.co_kwonlyargcount
        count += bool(code.co_flags & inspect.CO_VARARGS) + bool(code.co_flags & inspect.CO_VARKEYWORDS)
        arguments = (
            [_numeric_shape(frame.f_locals.get(name)) for name in code.co_varnames[:count]]
            if count <= _MAX_ITEMS else [None]
        )
        digest = None
        if None not in arguments:
            numeric = json.dumps(arguments, separators=(",", ":"), allow_nan=False).encode()
            digest = hashlib.blake2s(numeric, key=self.key, digest_size=8).hexdigest()
        stat[1].append(digest)


def decode_callbacks(output):
    if len(output) > REPORT_BYTES:
        return None
    try:
        stats = json.loads(output)
    except (ValueError, RecursionError):
        return None
    if type(stats) is not dict or len(stats) > _MAX_MOCKS:
        return None
    for name, info in stats.items():
        if (
            not _identifier(name) or type(info) is not list or len(info) != 2
            or type(info[0]) is not int or not 1 <= info[0] <= 100_000
            or type(info[1]) is not list or len(info[1]) != min(info[0], _MAX_CALLS)
            or not all(
                digest is None or (type(digest) is str and re.fullmatch(r"[a-f0-9]{16}", digest))
                for digest in info[1]
            )
        ):
            return None
    return stats


def _run_pytest(node, counter_paths=(), failure_line=None, callbacks=None):
    import pytest

    path = Path(node.split("::", 1)[0]).resolve()
    counter = (
        globals()["_counter_module"]["CounterTrace"](
            path, node, counter_paths, failure_line
        )
        if counter_paths
        else None
    )

    class Probe:
        reports = ()
        traces = None

        def pytest_collection_finish(self, session):
            if [item.nodeid for item in session.items] != [node]:
                pytest.exit("Expected precisely one selected test", returncode=4)

        @pytest.hookimpl(wrapper=True, tryfirst=True)
        def pytest_runtest_call(self, item):
            function = inspect.unwrap(item.obj)
            code = getattr(function, "__code__", None)
            unsupported = (
                inspect.CO_COROUTINE
                | inspect.CO_ASYNC_GENERATOR
                | inspect.CO_GENERATOR
                | inspect.CO_ITERABLE_COROUTINE
            )
            if (
                code is None
                or code.co_flags & unsupported
                or Path(code.co_filename).resolve() != path
                or sys.getprofile() is not None
            ):
                return (yield)
            events = 0

            def profile(frame, event, _value):
                nonlocal events
                events += 1
                if events >= 100_000:
                    self.traces = None
                    sys.setprofile(None)
                elif event == "return" and frame.f_code is code:
                    if callbacks is None:
                        self.traces = _locals_trace(frame)
                    else:
                        callbacks.complete = not callbacks.overflow
                    sys.setprofile(None)
                elif callbacks is not None and event == "call":
                    callbacks.observe(frame, code)

            tracer = (
                counter.tracer(code)
                if counter is not None and sys.gettrace() is None
                else None
            )
            sys.setprofile(profile)
            if tracer is not None:
                sys.settrace(tracer)
            try:
                return (yield)
            finally:
                sys.setprofile(None)
                if tracer is not None:
                    sys.settrace(None)

        @pytest.hookimpl(wrapper=True)
        def pytest_runtest_makereport(self, item, call):
            report = yield
            if counter is not None and item.nodeid == node and report.when == "call":
                counter.failure(report, call)
            return report

        def pytest_runtest_logreport(self, report):
            if report.nodeid == node and not hasattr(report, "wasxfail"):
                self.reports += ((report.when, report.outcome),)

    probe = Probe()
    os.environ.pop("PYTEST_ADDOPTS", None)
    sys.path.insert(0, os.getcwd())
    status = pytest.main(
        ["-o", "addopts=", "-p", "no:cacheprovider", "--", node],
        plugins=[probe],
    )
    expected = "passed" if status == 0 else "failed"
    if status in (0, 1) and probe.reports == (
        ("setup", "passed"),
        ("call", expected),
        ("teardown", "passed"),
    ):
        return (
            int(status),
            probe.traces,
            counter.report() if counter is not None else None,
        )
    return 4, None, None


def _main(node, counter_paths=(), failure_line=None, callback_key=None):
    # Keep all test output, even native stdout/stderr, out of the report stream.
    with os.fdopen(os.dup(1), "w") as report, open(os.devnull, "wb") as sink:
        os.dup2(sink.fileno(), 1)
        os.dup2(sink.fileno(), 2)
        if callback_key is not None:
            callbacks = _CallbackTrace(node, counter_paths, callback_key)
            status, _, _ = _run_pytest(node, callbacks=callbacks)
            if status == 0 and callbacks.complete:
                report.write(json.dumps(callbacks.stats, separators=(",", ":")))
            return status
        status, traces, counter = _run_pytest(node, counter_paths, failure_line)
        if traces is not None or counter is not None:
            data, cap = traces, REPORT_BYTES
            if counter_paths:
                data, cap = (
                    {"mocks": traces or {}, "counter": counter},
                    COUNTER_REPORT_BYTES,
                )
            payload = json.dumps(data, separators=(",", ":"), allow_nan=False)
            # Baseline windows after the selected candidate occurrence are optional.
            if counter is not None and counter[1] is None:
                while len(payload) > cap and len(counter[2]) > 1:
                    counter[2].pop()
                    payload = json.dumps(data, separators=(",", ":"), allow_nan=False)
            if counter_paths and len(payload) > cap:
                # Preserve the mock channel if the optional counter report is too large.
                data["counter"] = None
                payload = json.dumps(data, separators=(",", ":"), allow_nan=False)
            if len(payload) <= cap:
                report.write(payload)
        return status


if __name__ == "__main__":
    sys.exit(_main(sys.argv[1], *map(json.loads, sys.argv[2:])))
